// типограф: неразрывный пробел (U+00A0) там, где перенос строки рвёт смысл.
// Общий для scripts/typograph.mjs (тексты в json и шаблонах) и для строк,
// которые собираются в коде
export const NBSP = ' '

// короткие слова, которые не остаются в конце строки
const SHORT = [
  'в', 'во', 'и', 'с', 'со', 'к', 'ко', 'о', 'об', 'у', 'а', 'я',
  'на', 'по', 'за', 'от', 'до', 'из', 'не', 'ни', 'но',
  'для', 'без', 'под', 'над', 'при', 'про', 'или',
  'что', 'как', 'это', 'мы', 'вы', 'его', 'её', 'их',
]

// пробельная последовательность без неразрывного — её и заменяем
const SP = '[^\\S\\u00A0]+'

const RULES = [
  // короткое слово + пробел; слово отдельное — до него не буква и не цифра
  [new RegExp(`(?<![\\p{L}\\p{N}])(${SHORT.join('|')})${SP}(?=\\S)`, 'giu'), `$1${NBSP}`],
  // тире не переносится в начало строки
  [new RegExp(`(?<=\\S)${SP}(?=[—–](?:\\s|$))`, 'gu'), NBSP],
  // пробел внутри числа: 3 000, 12 500
  [new RegExp(`(?<=\\d)${SP}(?=\\d{3}(?!\\d))`, 'gu'), NBSP],
  // число и следующее слово или знак: 6 слайдов, 750 ₽, 30 %
  [new RegExp(`(?<=\\d)${SP}(?=[\\p{L}₽%€$])`, 'gu'), NBSP],
  // знак перед числом: + 200, № 5
  [new RegExp(`(?<=(?:^|\\s)[+−±×~≈№§])${SP}(?=\\d)`, 'gu'), NBSP],
  // реквизиты и сокращения: ИНН 3666…, ИП Мунтяну, т. е., т. д., т. п.
  [new RegExp(`(?<![\\p{L}])(ИНН|ОГРНИП|ОГРН|КПП|ИП)${SP}(?=\\S)`, 'gu'), `$1${NBSP}`],
  [new RegExp(`(?<![\\p{L}])т\\.${SP}(?=[едп]\\.)`, 'gu'), `т.${NBSP}`],
]

export function typo(text) {
  if (typeof text !== 'string') return text
  let out = text
  for (const [re, to] of RULES) out = out.replace(re, to)
  return out
}
